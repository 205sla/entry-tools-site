import { build } from "esbuild";
import React from "react";
import { renderToString } from "react-dom/server";
import { createHash } from "node:crypto";
import { cp, mkdir, readFile, writeFile, readdir } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { sites, exts, books } from "../data/catalog.js";
import { questions, choices, site, defaultTweaks } from "../data/site.js";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const at = name => resolve(root, name);
await mkdir(at(".build"), { recursive: true });
await build({
  absWorkingDir: root, entryPoints: ["app.jsx"], outfile: ".build/app.mjs",
  bundle: true, platform: "node", format: "esm", packages: "external",
  define: { "process.env.NODE_ENV": '"production"' },
});
const { default: App } = await import(pathToFileURL(at(".build/app.mjs")));
const body = renderToString(React.createElement(App));
await build({
  absWorkingDir: root, entryPoints: ["client.jsx"], outfile: "assets/site.js",
  bundle: true, minify: true, format: "iife", target: ["es2020"],
  legalComments: "inline", define: { "process.env.NODE_ENV": '"production"' },
});

const tools = [...sites, ...exts, ...books];
const schema = {
  "@context": "https://schema.org",
  "@graph": [
    {
      "@type": "WebSite", "@id": site.url + "#website", url: site.url,
      name: site.name, alternateName: "205 Entry Tools", inLanguage: "ko-KR",
      description: site.description, publisher: { "@id": "https://205.kr/#person" },
    },
    {
      "@type": "CollectionPage", "@id": site.url + "#webpage", url: site.url,
      name: site.title, description: site.description, inLanguage: "ko-KR",
      isPartOf: { "@id": site.url + "#website" },
      author: { "@id": "https://205.kr/#person" }, dateModified: site.updated,
      mainEntity: { "@id": site.url + "#catalog" },
      hasPart: [{ "@id": site.url + "#questions" }],
      citation: [site.source, "https://github.com/205sla/entry-vibe-coding"],
    },
    {
      "@type": "Person", "@id": "https://205.kr/#person", name: "이영호",
      alternateName: "205", url: "https://205.kr/", email: "205@205.kr",
      sameAs: ["https://github.com/205sla", "https://www.youtube.com/channel/UC8_yUqU2HnNkWBYfXhlWcWQ", "https://playentry.org/profile/56136825dadc91e1235b460d"],
    },
    {
      "@type": "ItemList", "@id": site.url + "#catalog", name: "엔트리 도구와 도서",
      numberOfItems: tools.length,
      itemListElement: tools.map((tool, i) => ({
        "@type": "ListItem", position: i + 1, name: tool.name || tool.title,
        description: tool.desc || tool.subtitle, url: tool.url || site.url + "#" + tool.id,
      })),
    },
    {
      "@type": "FAQPage", "@id": site.url + "#questions", url: site.url + "#questions",
      inLanguage: "ko-KR", isPartOf: { "@id": site.url + "#webpage" },
      mainEntity: questions.map(item => ({
        "@type": "Question", "@id": site.url + "#" + item.id, name: item.question,
        acceptedAnswer: { "@type": "Answer", text: item.answer },
      })),
    },
  ],
};
const escapeHtml = value => value.replaceAll("&", "&amp;").replaceAll('"', "&quot;").replaceAll("<", "&lt;").replaceAll(">", "&gt;");
const js = await readFile(at("assets/site.js"));
const css = await readFile(at("style.css"));
const version = createHash("sha256").update(js).update(css).digest("hex").slice(0, 12);
let template = await readFile(at("page.html"), "utf8");
const replacements = {
  TITLE: escapeHtml(site.title), DESCRIPTION: escapeHtml(site.description),
  STRUCTURED_DATA: JSON.stringify(schema, null, 2).replaceAll("<", "\\u003c"),
  APP_HTML: body, ASSET_VERSION: version, TWEAKS: JSON.stringify(defaultTweaks),
};
for (const [name, value] of Object.entries(replacements)) template = template.replaceAll(`{{${name}}}`, value);
if (/\{\{[A-Z_]+\}\}/.test(template)) throw new Error("Unresolved HTML template placeholder");
const html = "<!-- Generated by npm run build; edit page.html and components/, not this file. -->\n" + template;
await writeFile(at("index.html"), html);

const textLinks = list => list.map(item => `- [${item.name || item.title}](${item.url || site.url + "#" + item.id}): ${item.desc || item.subtitle}`).join("\n");
const llms = `# ${site.name}\n\n> ${site.description}\n\n제작자: 이영호(205). 엔트리 공식 서비스가 아닌 개인 프로젝트입니다.\n소개 내용 수정: ${site.updated}. 최신 기능과 이용 조건은 각 도구의 안내를 확인하세요.\n\n## 웹 서비스\n\n${textLinks(sites)}\n\n## 크롬 확장프로그램\n\n${textLinks(exts)}\n\n## 도서\n\n${textLinks(books)}\n\n## 목적별 안내\n\n${choices.map(item => `- [${item.title}](${site.url + item.href}): ${item.label}. ${item.text}`).join("\n")}\n\n## 자주 묻는 질문\n\n${questions.map(item => `### ${item.question}\n\n${item.answer}\n\n[관련 안내](${site.url + "#" + item.id})`).join("\n\n")}\n\n## 출처\n\n- [제작자 웹사이트](https://205.kr/)\n- [페이지 소스](${site.source})\n- [바이브코딩 프로젝트 문서](https://github.com/205sla/entry-vibe-coding)\n- [안내 기준과 출처](${site.url}#sources)\n`;
await writeFile(at("llms.txt"), llms);
await writeFile(at("sitemap.xml"), `<?xml version="1.0" encoding="UTF-8"?>\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>${site.url}</loc><lastmod>${site.updated}</lastmod></url>\n</urlset>\n`);

// Publish only site assets; source files, dependencies and tests stay out of the artifact.
await mkdir(at("dist/assets"), { recursive: true });
const files = ["index.html", "style.css", "robots.txt", "sitemap.xml", "llms.txt", "CNAME", "favicon.svg", "404.html", "indexnow-key.txt", ".nojekyll"];
files.push(...(await readdir(root)).filter(name => /^naver[a-z0-9]+\.html$/.test(name)));
for (const file of files) await cp(at(file), at("dist/" + file));
await cp(at("assets"), at("dist/assets"), { recursive: true });
console.log(`Built ${sites.length} services, ${exts.length} extensions, ${books.length} books and ${questions.length} answers into static HTML.`);
console.log(`HTML: ${Buffer.byteLength(html)} bytes; production JavaScript: ${js.length} bytes.`);
